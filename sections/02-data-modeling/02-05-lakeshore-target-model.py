# MAGIC %md
# MAGIC ## 3. The trap, live: informational constraints do NOT enforce
# MAGIC
# MAGIC We declared a PRIMARY KEY and a FOREIGN KEY. The docs say it plainly:
# MAGIC informational constraints "define relationships … and aren't enforced".
# MAGIC Only NOT NULL and CHECK enforce. Let's prove it — this insert references
# MAGIC a product that does not exist:

# COMMAND ----------

spark.sql("""
    INSERT INTO lakeshore.gold.fact_order_items
    VALUES ('O_GHOST', DATE'2026-08-01', 'C00001', 'P999', 1, 10.0, 10.0)
""")
ghost = spark.sql("""
    SELECT count(*) AS orphans FROM lakeshore.gold.fact_order_items f
    LEFT ANTI JOIN lakeshore.gold.dim_product p USING (product_id)
""").first()["orphans"]
print(f"Orphan fact rows accepted by the 'foreign key': {ghost}")
assert ghost >= 1, "expected the orphan row to be accepted"

# COMMAND ----------

# MAGIC %md
# MAGIC The FK **accepted the orphan**. On the exam, any option claiming a Delta
# MAGIC PK/FK "rejects" or "prevents" bad rows is wrong. Referential integrity in
# MAGIC the lakehouse is a *pipeline responsibility* (expectations, quality checks
# MAGIC — Sections 3 and 8), not a constraint's. Clean up:

# COMMAND ----------

# MAGIC %sql
# MAGIC DELETE FROM lakeshore.gold.fact_order_items WHERE order_id = 'O_GHOST';

