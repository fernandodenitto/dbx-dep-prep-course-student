# MAGIC %sql
# MAGIC -- The star in action: one hop from fact to dimension
# MAGIC SELECT p.category,
# MAGIC        sum(f.line_total) AS revenue,
# MAGIC        sum(f.quantity)   AS units
# MAGIC FROM lakeshore.gold.fact_order_items f
# MAGIC JOIN lakeshore.gold.dim_product p USING (product_id)
# MAGIC GROUP BY p.category
# MAGIC ORDER BY revenue DESC;

