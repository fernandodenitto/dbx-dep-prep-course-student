# MAGIC most: `order_date`, `product_id`.

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE TABLE IF NOT EXISTS lakeshore.gold.fact_order_items (
# MAGIC   order_id    STRING NOT NULL,
# MAGIC   order_date  DATE   NOT NULL,
# MAGIC   customer_id STRING NOT NULL,
# MAGIC   product_id  STRING NOT NULL,
# MAGIC   quantity    INT,
# MAGIC   unit_price  DOUBLE,
# MAGIC   line_total  DOUBLE,
# MAGIC   CONSTRAINT fact_oi_product_fk FOREIGN KEY (product_id)
# MAGIC     REFERENCES lakeshore.gold.dim_product (product_id)
# MAGIC )
# MAGIC CLUSTER BY (order_date, product_id)
# MAGIC COMMENT 'Order line items — grain: one row per line';

# COMMAND ----------

if spark.table("lakeshore.gold.fact_order_items").isEmpty():
    spark.sql("""
        INSERT INTO lakeshore.gold.fact_order_items
        SELECT order_id, CAST(order_ts AS DATE) AS order_date,
               customer_id, product_id, quantity, unit_price, line_total
        FROM lakeshore.silver.order_items
    """)
n = spark.table("lakeshore.gold.fact_order_items").count()
print(f"fact_order_items: {n} rows (count varies by cohort — by design)")

