# MAGIC ## 2. fact_order_items — the fact, liquid clustered
# MAGIC
# MAGIC Grain: one row per order line. Measures: quantity, line_total.
# MAGIC Foreign keys: product, customer, date. Layout: **liquid clustering**
# MAGIC (formerly you'd agonize between partitioning and Z-ORDER: lesson 2.7 has the
