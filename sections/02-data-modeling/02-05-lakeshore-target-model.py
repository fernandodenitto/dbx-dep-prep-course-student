# MAGIC %md
# MAGIC ## 1. dim_product — surrogate keys with identity columns
# MAGIC
# MAGIC Natural key: `product_id` from the source. Surrogate key: `product_key`,
# MAGIC generated by Delta (`GENERATED ALWAYS AS IDENTITY`) — stable, compact,
# MAGIC and under OUR control, not the source's. On 20 products this is ceremony;
# MAGIC on 20 million SKUs from 3 acquired companies, surrogate keys are survival.

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE TABLE IF NOT EXISTS lakeshore.gold.dim_product (
# MAGIC   product_key BIGINT GENERATED ALWAYS AS IDENTITY,
# MAGIC   product_id  STRING NOT NULL,
# MAGIC   name        STRING NOT NULL,
# MAGIC   category    STRING,
# MAGIC   unit_price  DOUBLE,
# MAGIC   CONSTRAINT dim_product_pk PRIMARY KEY (product_id)
# MAGIC )
# MAGIC COMMENT 'Product dimension — surrogate key + informational PK';

# COMMAND ----------

# Idempotent load: only fill an empty dimension
if spark.table("lakeshore.gold.dim_product").isEmpty():
    spark.sql("""
        INSERT INTO lakeshore.gold.dim_product (product_id, name, category, unit_price)
        SELECT product_id, name, category, unit_price
        FROM lakeshore.bronze.products
    """)
display(spark.sql("SELECT * FROM lakeshore.gold.dim_product ORDER BY product_key LIMIT 5"))

